import os
import sys
import sqlite3
import json

sys.stdout.reconfigure(encoding='utf-8')
sys.stderr.reconfigure(encoding='utf-8')

# Ensure vazus path is in sys.path
if "C:/vazus" not in sys.path and "C:\\vazus" not in sys.path:
    sys.path.insert(0, "C:/vazus")

from vazus_core.multimodal_knowledge import transcribe_and_chunk_media, generate_thumbnail, index_scenes_to_supergraph
from vazus_core.embeddings import UnifiedEmbeddingManager

def run_forensic_tests():
    print("=== STARTING FORENSIC BEHAVIORAL VERIFICATION ===")
    
    # 1. Test thumbnail generation on audio
    audio_file = r"C:\vazus\knowledge\telegram_courses\Курс _Покоритель Наташек 6_0_\media_174.oga"
    assert os.path.exists(audio_file), f"File not found: {audio_file}"
    
    thumb_path = generate_thumbnail(audio_file, 15.0, "C:/vazus/knowledge/.thumbnails/test_audio_thumb.jpg")
    print(f"[1] Thumbnail generated for audio: {thumb_path}")
    assert os.path.exists(thumb_path), "Thumbnail file was not created!"
    assert os.path.getsize(thumb_path) > 0, "Thumbnail file is empty!"
    
    # 2. Test transcribe and chunk media
    print(f"[2] Running transcribe_and_chunk_media on: {audio_file}")
    scenes = transcribe_and_chunk_media(audio_file, output_thumbnail_dir="C:/vazus/knowledge/.thumbnails")
    print(f"    Total scenes returned: {len(scenes)}")
    assert len(scenes) > 0, "No scenes generated by transcribe_and_chunk_media!"
    
    for sc in scenes:
        print(f"    - Scene ID: {sc['scene_id']}")
        print(f"      Time: {sc['start_sec']}s -> {sc['end_sec']}s (Duration: {sc['duration']}s)")
        print(f"      Transcript length: {len(sc['transcript'])} chars")
        print(f"      Transcript snippet: {sc['transcript'][:80]}...")
        print(f"      Thumbnail: {sc['thumbnail_path']}")
        assert len(sc['transcript']) > 0, "Transcript is empty!"
        assert os.path.exists(sc['thumbnail_path']), f"Thumbnail path missing: {sc['thumbnail_path']}"
    
    # 3. Test vector embedding & DB indexing
    print("[3] Running index_scenes_to_supergraph...")
    test_db = "C:/vazus/.agents/teamwork_preview_auditor_m1_1/audit_test.db"
    if os.path.exists(test_db):
        os.remove(test_db)
        
    count = index_scenes_to_supergraph(scenes, db_path=test_db)
    print(f"    Indexed {count} scenes to test DB: {test_db}")
    assert count == len(scenes), f"Expected {len(scenes)} indexed, got {count}"
    
    conn = sqlite3.connect(test_db)
    cur = conn.cursor()
    nodes = cur.execute("SELECT id, name, domain, node_type, properties, embedding_json FROM kg_nodes").fetchall()
    print(f"    DB kg_nodes count: {len(nodes)}")
    assert len(nodes) == len(scenes), "Node count mismatch in database!"
    
    for n in nodes:
        node_id, name, domain, node_type, props_str, emb_str = n
        assert domain == "multimodal_av", f"Incorrect domain: {domain}"
        assert node_type == "MediaScene", f"Incorrect node_type: {node_type}"
        
        emb = json.loads(emb_str)
        assert len(emb) == 768, f"Embedding dimension is {len(emb)}, expected 768!"
        print(f"    - Verified Node {node_id}: {name} | 768D Vector dim verified OK!")
        
    edges = cur.execute("SELECT source_id, target_id, relation FROM kg_edges").fetchall()
    print(f"    DB kg_edges count: {len(edges)}")
    assert len(edges) > 0, "No edges inserted into database!"
    conn.close()
    
    print("=== ALL FORENSIC VERIFICATION CHECKS PASSED SUCCESSFULLY ===")

if __name__ == "__main__":
    run_forensic_tests()
