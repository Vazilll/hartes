def sanitize_text(text):
    # Remove any control characters invalid in XML
    return re.sub(r'[\x00-\x08\x0B\x0C\x0E-\x1F\x7F-\x9F]', '', text)

def generate_files():
    sanitized_text = sanitize_text(MARKDOWN_TEXTBOOK)

    # 1. Save Markdown
    with open(MD_PATH, 'w', encoding='utf-8') as f:
        f.write(sanitized_text)
    print(f"Markdown master textbook saved to: {MD_PATH}")

    # 2. Save DOCX
    doc = docx.Document()
    for section in doc.sections:
        section.page_width = Inches(8.27)
        section.page_height = Inches(11.69)
        section.top_margin = Inches(0.79)
        section.bottom_margin = Inches(0.79)
        section.left_margin = Inches(0.79)
        section.right_margin = Inches(0.79)

    style_normal = doc.styles['Normal']
    style_normal.font.name = 'Calibri'
    style_normal.font.size = Pt(11)
    style_normal.font.color.rgb = RGBColor(0x22, 0x22, 0x22)
    style_normal.paragraph_format.line_spacing = 1.15
    style_normal.paragraph_format.space_after = Pt(6)

    # Process markdown lines into docx
    lines = sanitized_text.split('\n')
    for line in lines:
        if line.startswith('# '):
            h = doc.add_heading(line[2:], level=1)
            h.runs[0].font.color.rgb = RGBColor(0x00, 0x56, 0x91)
        elif line.startswith('## '):
            h = doc.add_heading(line[3:], level=1)
            h.runs[0].font.color.rgb = RGBColor(0x00, 0x56, 0x91)
        elif line.startswith('### '):
            h = doc.add_heading(line[4:], level=2)
            h.runs[0].font.color.rgb = RGBColor(0x11, 0x11, 0x11)
        elif line.startswith('#### '):
            h = doc.add_heading(line[5:], level=3)
            h.runs[0].font.color.rgb = RGBColor(0x33, 0x33, 0x33)
        elif line.startswith('---'):
            doc.add_paragraph().paragraph_format.space_after = Pt(4)
        else:
            _p = doc.add_paragraph(line)

    doc.save(DOCX_PATH)
    print(f"DOCX textbook saved to: {DOCX_PATH}")

    # 3. Save PDF via ReportLab
    pdfmetrics.registerFont(TTFont('Arial', r'C:\Windows\Fonts\arial.ttf'))
    pdfmetrics.registerFont(TTFont('Arial-Bold', r'C:\Windows\Fonts\arialbd.ttf'))
    pdfmetrics.registerFont(TTFont('Courier', r'C:\Windows\Fonts\couri.ttf'))

    styles = getSampleStyleSheet()
    COLOR_PRIMARY = colors.HexColor('#005691')
    COLOR_DARK = colors.HexColor('#111111')

    style_title = ParagraphStyle('TTitle', parent=styles['Normal'], fontName='Arial-Bold', fontSize=14, leading=18, textColor=COLOR_DARK, spaceAfter=8)
    style_h1 = ParagraphStyle('TH1', parent=styles['Normal'], fontName='Arial-Bold', fontSize=11, leading=14, textColor=COLOR_PRIMARY, spaceBefore=12, spaceAfter=6, keepWithNext=True)
    style_h2 = ParagraphStyle('TH2', parent=styles['Normal'], fontName='Arial-Bold', fontSize=9.5, leading=12.5, textColor=COLOR_DARK, spaceBefore=8, spaceAfter=4, keepWithNext=True)
    style_body = ParagraphStyle('TBody', parent=styles['Normal'], fontName='Arial', fontSize=8.5, leading=11.5, textColor=COLOR_DARK, spaceAfter=4)
    style_code = ParagraphStyle('TCode', parent=styles['Normal'], fontName='Courier', fontSize=7, leading=8.5, textColor=colors.HexColor('#00FF66'))

    story = []
    in_code_block = False
    code_lines = []

    for line in lines:
        if line.startswith('```'):
            if in_code_block:
                # End code block
                code_text = "<br/>".join(code_lines).replace(" ", "&nbsp;").replace("<", "&lt;").replace(">", "&gt;")
                t_code = Table([[Paragraph(code_text, style_code)]], colWidths=[510])
                t_code.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#1E1E1E')),
                    ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#333333')),
                    ('TOPPADDING', (0, 0), (-1, -1), 5),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
                    ('LEFTPADDING', (0, 0), (-1, -1), 6),
                    ('RIGHTPADDING', (0, 0), (-1, -1), 6),
                ]))
                story.append(t_code)
                story.append(Spacer(1, 4))
                code_lines = []
                in_code_block = False
            else:
                in_code_block = True
                code_lines = []
            continue

        if in_code_block:
            code_lines.append(line)
            continue

        if line.startswith('# '):
            story.append(Paragraph(line[2:], style_title))
            story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY, spaceBefore=2, spaceAfter=6))
        elif line.startswith('## '):
            story.append(Paragraph(line[3:], style_h1))
        elif line.startswith('### '):
            story.append(Paragraph(line[4:], style_h2))
        elif line.startswith('---'):
            story.append(Spacer(1, 4))
        else:
            if line.strip():
                formatted = line.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                formatted = re.sub(r'\*\*(.*?)\*\*', r'<b>\1</b>', formatted)
                formatted = re.sub(r'\*(.*?)\*', r'<i>\1</i>', formatted)
                formatted = re.sub(r'`(.*?)`', r'<code>\1</code>', formatted)
                story.append(Paragraph(formatted, style_body))

    doc_pdf = SimpleDocTemplate(PDF_PATH, pagesize=A4, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    doc_pdf.build(story)
    print(f"PDF textbook saved to: {PDF_PATH}")

if __name__ == "__main__":
    generate_files()
