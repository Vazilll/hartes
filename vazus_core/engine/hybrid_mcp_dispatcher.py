@dataclass
class HybridExecutionPlan:
    """Structured execution plan generated by Julia System-1 Router."""

    tier: str  # "tier0_direct", "tier1_slm", "tier2_cloud"
    target_hub: str
    hub_name: str
    canonical_domain: str
    confidence: float
    disclosed_mcp_tools: List[str]
    selected_skill: Optional[str]
    skill_tree_next: List[str]
    requires_new_skill: bool
    direct_execution_result: Optional[Any] = None
    slm_delegation_target: Optional[str] = None  # "rwkv7", "timesfm3", None
    token_cost: int = 0
    latency_ms: float = 0.0
    device_used: str = "NPU"
    routing_summary: str = ""
    speculative_prediction: Optional["SpeculativePrediction"] = None
    """Pre-fetched speculative tool prediction (TimesFM 3.0 + Julia NPU)."""


# ════════════════════════════════════════════════════════════════════════════
# 2. Hybrid MCP Dispatcher Implementation
# ════════════════════════════════════════════════════════════════════════════

class HybridMCPDispatcher:
    """
    Unified System-1 Gateway integrating Julia Router, MCP Tool Pruning,
    and 3-Tier Multi-Level Hybrid Orchestration.
    """

    def __init__(self, router: Optional[JuliaRouter] = None, db_path: str = "C:/vazus/services/memory/vazus.db"):
        self.router = router or JuliaRouter()
        self.db_path = db_path
        # Pre-warm SpeculativeToolPredictor once so first query is fast
        self._speculative: Optional["SpeculativeToolPredictor"] = None
        if _SPECULATIVE_AVAILABLE:
            try:
                self._speculative = SpeculativeToolPredictor()
                logger.info("SpeculativeToolPredictor ready (TimesFM 3.0 warm)")
            except Exception as exc:
                logger.warning("SpeculativeToolPredictor init failed: %s", exc)

    def dispatch(self, user_query: str) -> HybridExecutionPlan:
        """
        Processes user query in < 15ms on Intel NPU, formulating an optimal hybrid execution plan.
        Speculatively predicts next tools via TimesFM + Julia before routing.
        """
        start_t = time.perf_counter()

        # Step 0: Speculative prefetch (TimesFM 3.0 warm = ~400ms, cold = ~8s)
        speculative: Optional["SpeculativePrediction"] = None
        if self._speculative is not None:
            try:
                speculative = self._speculative.predict_for_query(user_query, top_k=3)
                logger.debug(
                    "Speculative: domain=%s tools=%s conf=%.2f latency=%.0fms",
                    speculative.domain,
                    speculative.predicted_tools,
                    speculative.confidence,
                    speculative.latency_ms,
                )
            except Exception as exc:
                logger.warning("Speculative prediction failed: %s", exc)

        # Step 1: NPU Domain Routing (<1.5 ms)
        domain_dec = self.router.route(user_query)
        domain = domain_dec.domain
        hub_key = DOMAIN_TO_HUB.get(domain, "hub_code")
        hub_info = SUPER_HUBS[hub_key]

        # Step 2: Skill Tree & Gap Detection (<1.5 ms)
        skill_dec = self.router.route_skill(user_query)

        # Step 3: Check Tier 0 Direct Reflex (<0.1 ms)
        action_dec = self.router.route_routine_action(user_query)

        if action_dec.is_routine:
            # Execute Tier 0 immediately without touching cloud LLM!
            direct_res = self._execute_tier0(action_dec)
            elapsed_ms = (time.perf_counter() - start_t) * 1000.0

            return HybridExecutionPlan(
                tier="tier0_direct",
                target_hub=hub_key,
                hub_name=hub_info["name"],
                canonical_domain=domain,
                confidence=domain_dec.confidence,
                disclosed_mcp_tools=[],
                selected_skill=skill_dec.selected_skill,
                skill_tree_next=skill_dec.next_in_tree,
                requires_new_skill=skill_dec.requires_new_skill,
                direct_execution_result=direct_res,
                token_cost=0,  # Zero-Token execution!
                latency_ms=round(elapsed_ms, 2),
                device_used=action_dec.device_used,
                routing_summary=f"Tier-0 Reflex Executed ({action_dec.action_type}: {action_dec.target_tool}) in {elapsed_ms:.2f}ms with 0 tokens.",
                speculative_prediction=speculative,
            )

        # Step 4: Check Tier 1 Time-Series / Local SLM Triggers
        q_lower = user_query.lower()
        if any(w in q_lower for w in ("прогноз", "тренд", "траектори", "динамик", "forecast")):
            # Delegate to TimesFM 3.0
            elapsed_ms = (time.perf_counter() - start_t) * 1000.0
            return HybridExecutionPlan(
                tier="tier1_slm",
                target_hub=hub_key,
                hub_name=hub_info["name"],
                canonical_domain=domain,
                confidence=domain_dec.confidence,
                disclosed_mcp_tools=["timesfm_forecaster"],
                selected_skill=skill_dec.selected_skill,
                skill_tree_next=skill_dec.next_in_tree,
                requires_new_skill=skill_dec.requires_new_skill,
                slm_delegation_target="timesfm3",
                token_cost=0,
                latency_ms=round(elapsed_ms, 2),
                device_used="Intel CPU / TimesFM 3.0",
                routing_summary="Tier-1 SLM Forecasting Activated (TimesFM 3.0).",
                speculative_prediction=speculative,
            )

        # Step 5: Tier 2 Cloud Escalation with Progressive Tool Disclosure
        tool_dec = self.router.route_tool(user_query)
        selected_tool = tool_dec.selected_tool
        disclosed = [selected_tool] + tool_dec.fallback_tools[:2]

        # Enrich disclosed tools with speculative predictions (deduplicated)
        if speculative and speculative.predicted_tools:
            for pred_tool in speculative.predicted_tools[:2]:
                if pred_tool and pred_tool not in disclosed:
                    disclosed.append(pred_tool)

        elapsed_ms = (time.perf_counter() - start_t) * 1000.0

        return HybridExecutionPlan(
            tier="tier2_cloud",
            target_hub=hub_key,
            hub_name=hub_info["name"],
            canonical_domain=domain,
            confidence=domain_dec.confidence,
            disclosed_mcp_tools=disclosed,
            selected_skill=skill_dec.selected_skill,
            skill_tree_next=skill_dec.next_in_tree,
            requires_new_skill=skill_dec.requires_new_skill,
            token_cost=150,  # ~150 tokens for 2-3 tools vs 8000 tokens for all 80 tools!
            latency_ms=round(elapsed_ms, 2),
            device_used=domain_dec.metadata.get("device_used", "NPU"),
            routing_summary=f"Tier-2 Cloud Reasoning (Disclosed {len(disclosed)} of 80+ tools: {disclosed}) in {elapsed_ms:.2f}ms.",
            speculative_prediction=speculative,
        )


    def _execute_tier0(self, action: RoutineActionDecision) -> Dict[str, Any]:
        """Executes zero-token deterministic operations locally."""
        if action.action_type == "run_command" and action.suggested_command:
            # Safe allowed commands
            if "pytest" in action.suggested_command:
                proc = subprocess.run(
                    [r"C:\vazus\.venv\Scripts\pytest.exe", r"C:\vazus\tests\test_julia_router.py", "-q"],
                    capture_output=True,
                    text=True,
                )
                return {
                    "action": "pytest",
                    "exit_code": proc.returncode,
                    "output": proc.stdout.strip()[:300],
                }
            elif "clip_ocr" in action.suggested_command:
                return {
                    "action": "clip_ocr",
                    "status": "ready",
                    "note": "PIL ImageGrab clipboard OCR entrypoint",
                }

        elif action.action_type == "mcp_call":
            if "tinkoff" in str(action.target_tool):
                try:
                    con = sqlite3.connect(self.db_path)
                    cur = con.cursor()
                    cur.execute("SELECT COUNT(*), COALESCE(SUM(amount_rub), 0) FROM finance_transactions")
                    cnt, total = cur.fetchone()
                    con.close()
                    return {"action": "finance_query", "tx_count": cnt, "total_rub": total}
                except Exception as e:
                    return {"error": str(e)}

            elif "academic" in str(action.target_tool):
                try:
                    con = sqlite3.connect(self.db_path)
                    cur = con.cursor()
                    cur.execute("SELECT COUNT(*) FROM user_liabilities")
                    debts = cur.fetchone()[0]
                    con.close()
                    return {"action": "academic_query", "active_debts": debts, "stage1_deadline": "15.10.2026"}
                except Exception as e:
                    return {"error": str(e)}

        return {"action": "generic_reflex", "status": "executed"}
